test('My Deals has title-aligned search and independently accessible sticky T/C roles',()=>{
  assert.match(overview,/<h1[^>]*>[\s\S]*?My Deals\s*<\/h1>/)
  // Mirrors Showroom: search stays visible next to the title at every width.
  assert.match(overview,/<header className="sticky top-14 md:top-16[^"]*flex min-h-\[70px\] flex-wrap items-center/)
  assert.match(overview,/<DiscoverySearch id="my-deals-search" value=\{search\} onChange=\{setSearch\}/)
  assert.match(overview,/min-w-\[10rem\] max-w-\[340px\] flex-\[1_1_12rem\]/)
  assert.doesNotMatch(overview,/searchOpen|Close deals search/)
  assert.match(overview,/aria-label="My Deals view"/)
  assert.match(overview,/\{title\}<\/h2>/)
  assert.match(overview,/aria-label="My Deals display controls"/)
  const toolbar=overview.slice(overview.indexOf('aria-label="My Deals display controls"'),
    overview.indexOf('<section className="space-y-3" aria-label="My Deals">'))
  assert.match(overview,/<div className="md:sticky md:top-\[134px\][^\"]*items-center justify-between[^\"]*" aria-label="My Deals display controls">/)
  assert.match(toolbar,/aria-label="Deal role modes"/)
  assert.match(toolbar,/aria-label="My Deals view"/)
  assert.match(toolbar,/aria-label="Grid view"/)
  assert.match(toolbar,/aria-label="List view"/)
  assert.match(toolbar,/value==='talent'\?'T':'C'/)
  assert.doesNotMatch(toolbar,/flex-wrap/)
  assert.doesNotMatch(overview,/CompactPageHeader/)
})
