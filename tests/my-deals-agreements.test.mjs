import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8')
const overview=read('src/pages/MyDeals.jsx')
const detail=read('src/pages/DealDetails.jsx')
const agreement=read('src/pages/DealAgreement.jsx')
const document=read('src/lib/dealAgreementDocument.js')
const server=read('api/_lib/dealAgreement.js')
const cancel=read('api/_lib/dealCancellation.js')
const route=read('api/escrows/index.js')

test('My Deals has title-aligned search and independently accessible sticky T/C roles',()=>{
  assert.match(overview,/<h1[^>]*>.*?My Deals<\/h1>/)
  assert.match(overview,/aria-label=\{searchOpen\?'Close deals search':'Search deals'\}/)
  assert.match(overview,/aria-label="Deal role modes"/)
  assert.match(overview,/sticky top-\[126px\] md:top-\[134px\]/)
  assert.match(overview,/value==='talent'\?'T':'C'/)
  assert.doesNotMatch(overview,/CompactPageHeader/)
})
test('My Deals supports persistent flat grid and list with one detail action per transaction',()=>{
  assert.match(overview,/aria-label="Grid view"/)
  assert.match(overview,/aria-label="List view"/)
  assert.match(overview,/chombutar_deals_view/)
  assert.match(overview,/aria-label=\{viewMode==='grid'\?'Deals grid':'Deals list'\}/)
  assert.match(overview,/View details <ChevronRight/)
  assert.doesNotMatch(overview,/Deals Chat|<MessageCircle/)
  assert.doesNotMatch(overview,/>Agreement<\/Link>/)
})
test('deal detail hides discovery search and routes Agreement/history/cancellation per deal',()=>{
  assert.match(detail,/>Deals details<\/h1>/)
  assert.doesNotMatch(detail,/CompactPageHeader/)
  assert.match(detail,/Deal transaction sections/)
  assert.match(detail,/\['agreement','Agreement'\]/)
  assert.match(detail,/\['history','Chat & negotiation history'\]/)
  assert.match(detail,/\['cancel','Cancel deal'\]/)
  assert.match(detail,/detailSection==='history'/)
  assert.match(detail,/\/messages\?escrow=\$\{thread.id\}/)
  assert.match(detail,/\/deals\/\$\{thread.id\}\/agreement/)
  assert.match(detail,/How escrow works/)
  assert.match(detail,/Request cancellation \/ Open dispute/)
  assert.doesNotMatch(detail,/Negotiation<\/Link>/)
})
test('new cancellation is limited to unfunded not-locked transactions, stores reason and notifies other party',()=>{
  assert.match(cancel,/status!=='not_funded'/)
  assert.match(cancel,/checkout_locked_at\|\|record.checkout_reference/)
  assert.match(cancel,/FOR UPDATE/)
  assert.match(cancel,/deal_cancellation_records/)
  assert.match(cancel,/UPDATE escrows SET status='cancelled'/)
  assert.match(cancel,/notifyUser/)
  assert.match(route,/cancel_unfunded_deal/)
  assert.match(read('db/patch-deal-cancellation-records-2026-10.sql'),/cancelled_by/)
})
test('agreement and verification pages are separate; QR references live signed status',()=>{
  const app=read('src/App.jsx')
  assert.match(app,/path="\/deals\/:dealId\/agreement"/)
  assert.match(app,/path="\/deals\/verify-agreement"/)
  assert.match(agreement,/createAgreementHtml/)
  assert.match(agreement,/QRCode\.toDataURL/)
  assert.match(agreement,/Print \/ Save as PDF/)
  assert.match(agreement,/Download \(\.html\)/)
  assert.match(server,/createHmac\('sha256'/)
  assert.match(server,/timingSafeEqual/)
  assert.match(server,/row.status==='secured'/)
  assert.match(server,/client_id&&userId!==row.talent_id/)
  assert.match(route,/verify_agreement/)
  assert.match(route,/deal_agreement/)
  assert.match(document,/NOT AN ACTIVE ENTRY PASS/)
  assert.match(document,/No handwritten or separate electronic signature/)
  assert.match(document,/venue approval/)
  assert.doesNotMatch(document,/guaranteed admission|legally binding by virtue/)
})
