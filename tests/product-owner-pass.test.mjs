test('wallet transfer is ChombuTar-only and idempotent with a paired atomic debit and credit',()=>{
 const backend=source('api/_lib/walletPeerTransfers.js')
 const migration=source('db/patch-wallet-peer-transfers-2026-11.sql')
 const route=source('api/escrows/index.js')
 const ui=source('src/components/WalletTransferDialog.jsx')
 assert.match(backend,/FROM users WHERE LOWER\(username\)=LOWER\(\$1\)/)
 assert.match(backend,/ON CONFLICT \(sender_id,client_token\) DO NOTHING/)
 assert.match(backend,/client\.query\('BEGIN'\)/)
 assert.match(backend,/ORDER BY user_id FOR UPDATE/)
 assert.match(backend,/await debitWallet\(client/)
 assert.match(backend,/await creditWallet\(client/)
 assert.match(backend,/await client\.query\('COMMIT'\)/)
 assert.match(backend,/await client\.query\('ROLLBACK'\)/)
 assert.match(migration,/UNIQUE \(sender_id, client_token\)/)
 assert.match(migration,/wallet_transfer_sent','wallet_transfer_received/)
 assert.match(migration,/transfer_id/)
 assert.match(route,/wallet_recipient/)
 assert.match(route,/wallet_peer_transfer/)
 assert.match(route,/counterparty_username/)
 assert.match(ui,/api\.findWalletRecipient/)
 assert.match(ui,/api\.sendWalletTransfer/)
 assert.match(ui,/crypto\.randomUUID/)
 assert.match(ui,/cannot be undone/)
})
